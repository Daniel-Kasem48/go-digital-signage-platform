package channel_schedule

import (
	"digital-signage/internal/db"
	models "digital-signage/internal/db/autogenerated"
	"digital-signage/internal/handlers"
	content_sync "digital-signage/internal/modules/content-sync"
	"digital-signage/internal/modules/utils"
	"fmt"
	"github.com/jackc/pgx/v5/pgxpool"
	"github.com/labstack/echo/v4"
	"net/http"
)

type ChannelScheduleController struct {
	dataSourceService *db.DatasourceService
	channelScheduleService   *ChannelScheduleService
	validator      *handlers.CustomValidator
	contentSyncService *content_sync.ContentSyncService
	dbPool 			*pgxpool.Pool
}

func NewChannelScheduleController(
	dataSourceService *db.DatasourceService,
	validator     *handlers.CustomValidator,
	channelScheduleService *ChannelScheduleService,
	dbPool 			*pgxpool.Pool,
	contentSyncService *content_sync.ContentSyncService,

	) *ChannelScheduleController {
	return &ChannelScheduleController{
		dataSourceService: dataSourceService,
		validator     : validator,
		channelScheduleService: channelScheduleService,
		dbPool: dbPool,
		contentSyncService: contentSyncService,
	}
}

func (c *ChannelScheduleController) RegisterRoutes(parent *echo.Group) {
	g := parent.Group("/channels")

	g.GET("/:id/schedules", c.List)
	g.POST("/:id/schedules", c.SetSchedules)
	
	// Add standalone schedule routes
	scheduleGroup := parent.Group("/channel-schedules")
	scheduleGroup.POST("", c.Create)
	scheduleGroup.DELETE("/:id", c.Delete)
}

func (c *ChannelScheduleController) RegisterBackendRoutes(parent *echo.Group) {
	g := parent.Group("/channels")

	g.GET("/:id/schedules", c.List)
	g.POST("/:id/schedules", c.SetSchedules)
	
	// Add standalone schedule routes for backend
	scheduleGroup := parent.Group("/channel-schedules")
	scheduleGroup.POST("", c.Create)
	scheduleGroup.DELETE("/:id", c.Delete)
}

func (c *ChannelScheduleController) SetSchedules(ctx echo.Context) error {
	ID := ctx.Param("id")

	channelId, err := utils.ParseAndConvertUUID(ID)
	if err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "Invalid UUID format")
	}

	input := new(CreateManyChannelScheduleDto)
	if err := ctx.Bind(input); err != nil {
		return ctx.JSON(http.StatusBadRequest, map[string]string{"error": "Invalid input"+err.Error()})
	}

	if err := c.validator.ValidateAndReturnErrors(input); err != nil {
		return err
	}
	var createParams []models.InsertChannelScheduleParams

	for _, scheduleInput := range input.Schedules {
		createParams = append(createParams, models.InsertChannelScheduleParams{
			StartDatetime: scheduleInput.StartDatetime,
			EndDatetime:   scheduleInput.EndDatetime,
			ChannelID:     channelId,
			PlaylistID:    scheduleInput.PlaylistID,
			Day:           int32(scheduleInput.Day),
		})
	}

	err = c.channelScheduleService.SetSchedulesTransaction(ctx, c.dbPool, createParams, channelId)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	// Notify devices affected by this channel schedule change
	if err := c.contentSyncService.NotifyDevicesByChannelId(ctx, channelId); err != nil {
		fmt.Printf("Failed to notify devices of channel schedule change: %v\n", err)
	}

	return ctx.JSON(http.StatusOK, "created")
}

func (c *ChannelScheduleController) List(ctx echo.Context) error {
	ID := ctx.Param("id")

	uuId, err := utils.ParseAndConvertUUID(ID)
	if err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "Invalid UUID format")
	}

	mtq ,err:= db.NewMultiTenantQuerierByContext(ctx,c.dbPool)
	if err != nil {
		return err
	}

	entities, err := mtq.Querier.GetChannelSchedulesByChannelID(ctx.Request().Context(),uuId)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}
	if entities == nil {
		entities = []models.ChannelSchedule{}
	}

	return ctx.JSON(http.StatusOK, entities)
}

func (c *ChannelScheduleController) Create(ctx echo.Context) error {
	input := new(CreateChannelScheduleDto)
	if err := ctx.Bind(input); err != nil {
		return ctx.JSON(http.StatusBadRequest, map[string]string{"error": "Invalid input: " + err.Error()})
	}

	if err := c.validator.ValidateAndReturnErrors(input); err != nil {
		return err
	}

	mtq, err := db.NewMultiTenantQuerierByContext(ctx, c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	createParams := models.InsertChannelScheduleParams{
		StartDatetime: input.StartDatetime,
		EndDatetime:   input.EndDatetime,
		ChannelID:     input.ChannelID,
		PlaylistID:    input.PlaylistID,
		Day:           int32(input.Day),
	}

	_, err = mtq.Querier.InsertChannelSchedule(ctx.Request().Context(), []models.InsertChannelScheduleParams{createParams})
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "Failed to create schedule: " + err.Error())
	}

	// Notify devices affected by this channel schedule change
	if err := c.contentSyncService.NotifyDevicesByChannelId(ctx, input.ChannelID); err != nil {
		fmt.Printf("Failed to notify devices of channel schedule change: %v\n", err)
	}

	// Return success
	return ctx.JSON(http.StatusOK, map[string]interface{}{
		"message": "Schedule created successfully"})
}

func (c *ChannelScheduleController) Delete(ctx echo.Context) error {
	ID := ctx.Param("id")

	scheduleId, err := utils.ParseAndConvertUUID(ID)
	if err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "Invalid UUID format")
	}

	mtq, err := db.NewMultiTenantQuerierByContext(ctx, c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	// Get the schedule first to find the channel ID for notification
	schedule, err := mtq.Querier.GetChannelScheduleByID(ctx.Request().Context(), scheduleId)
	if err != nil {
		return echo.NewHTTPError(http.StatusNotFound, "Schedule not found")
	}

	// Delete the schedule
	err = mtq.Querier.DeleteChannelSchedule(ctx.Request().Context(), scheduleId)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "Failed to delete schedule: " + err.Error())
	}

	// Notify devices affected by this channel schedule change
	if err := c.contentSyncService.NotifyDevicesByChannelId(ctx, schedule.ChannelID); err != nil {
		fmt.Printf("Failed to notify devices of channel schedule change: %v\n", err)
	}

	// Return success
	return ctx.JSON(http.StatusOK, map[string]interface{}{
		"message": "Schedule deleted successfully"})
}