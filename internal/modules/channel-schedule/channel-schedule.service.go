
package channel_schedule

import (
	"digital-signage/internal/db"
	models "digital-signage/internal/db/autogenerated"
	"github.com/jackc/pgx/v5/pgtype"
	"github.com/jackc/pgx/v5/pgxpool"
	"github.com/labstack/echo/v4"
)

type ChannelScheduleService struct {
	queries *models.Queries
	dbPool *pgxpool.Pool

}

func NewChannelScheduleService(pool *pgxpool.Pool,
	dbPool *pgxpool.Pool,

	) *ChannelScheduleService {
	queries := models.New(pool) // Initialize the queries using sqlc-generated code
	return &ChannelScheduleService{queries: queries, dbPool: dbPool}
}


func (s *ChannelScheduleService) SetSchedulesTransaction(ctx echo.Context, pool *pgxpool.Pool, createParams []models.InsertChannelScheduleParams, channelId pgtype.UUID) error {
	// Acquire a connection from the pool
	conn, err := pool.Acquire(ctx.Request().Context())
	if err != nil {
		return err
	}
	defer conn.Release()

	// Start a transaction
	tx, err := conn.Begin(ctx.Request().Context())
	if err != nil {
		return err
	}
	defer tx.Rollback(ctx.Request().Context()) // Rollback if Commit is not called

	// Create transaction-aware Queries instance
	mtq ,err:= db.NewMultiTenantQuerierByContext(ctx,s.dbPool)
	if err != nil {
		return err
	}

	qtx := mtq.Querier.WithTx(tx)
	err = qtx.DeleteSchedulesByChannelID(ctx.Request().Context(), channelId)
	_,err = qtx.InsertChannelSchedule(ctx.Request().Context(), createParams)

	// Commit the transaction
	if err := tx.Commit(ctx.Request().Context()); err != nil {
		return err
	}

	return nil
}