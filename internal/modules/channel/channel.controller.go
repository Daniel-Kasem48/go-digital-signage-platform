var channelUUIDRegex = regexp.MustCompile(`[0-9a-fA-F-]{36}$`)

func extractChannelIDFromFriendlyRef(ref string) (string, bool) {
	matched := channelUUIDRegex.FindString(ref)
	if matched == "" {
		return "", false
	}
	return matched, true
}

func shortCodeFromChannelID(channelID string) string {
	var hash uint32 = 5381
	for _, ch := range strings.ToLower(channelID) {
		if ch == '-' {
			continue
		}
		hash = ((hash << 5) + hash) + uint32(ch)
	}

	const base36Six = 2176782336 // 36^6
	codeNum := uint64(hash % base36Six)
	code := strings.ToUpper(strconv.FormatUint(codeNum, 36))
	if len(code) >= 6 {
		return code[len(code)-6:]
	}
	return strings.Repeat("0", 6-len(code)) + code
}

func resolveTenantForLive(ctx echo.Context) string {
	if queryTenant := strings.TrimSpace(ctx.QueryParam("t")); queryTenant != "" {
		return queryTenant
	}
	if headerTenant := strings.TrimSpace(ctx.Request().Header.Get("X-Tenant-ID")); headerTenant != "" {
		return headerTenant
	}
	host := ctx.Request().Host
	if idx := strings.Index(host, ":"); idx != -1 {
		host = host[:idx]
	}
	parts := strings.Split(host, ".")
	if len(parts) >= 3 && parts[0] != "www" && parts[0] != "" {
		return parts[0]
	}
	return "test_schema"
}

func (c *ChannelController) serveHostedPlayerByID(ctx echo.Context, tenant string, channelIDStr string) error {
	channelID, err := utils.ParseAndConvertUUID(channelIDStr)
	if err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "invalid channel id")
	}

	requestCtx := context.WithValue(ctx.Request().Context(), "tenantSlug", tenant)
	ctx.SetRequest(ctx.Request().WithContext(requestCtx))

	mtq, err := db.NewMultiTenantQuerierByContext(ctx, c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	channel, err := mtq.Querier.GetChannelById(ctx.Request().Context(), channelID)
	if err != nil {
		return echo.NewHTTPError(http.StatusNotFound, "channel not found")
	}

	channelNameBytes, _ := json.Marshal(channel.Name)
	channelIDBytes, _ := json.Marshal(channelIDStr)
	tenantBytes, _ := json.Marshal(tenant)

	return c.renderHostedPage(ctx, tenantBytes, channelIDBytes, channelNameBytes)
}

// ServeHostedPlayer renders a hosted, TV-friendly page that plays channel content directly by channel URL.
func (c *ChannelController) ServeHostedPlayer(ctx echo.Context) error {
	tenant := strings.TrimSpace(ctx.Param("tenant"))
	channelRef := strings.TrimSpace(ctx.Param("channelRef"))
	if tenant == "" || channelRef == "" {
		return echo.NewHTTPError(http.StatusBadRequest, "tenant and channel reference are required")
	}

	channelIDStr, ok := extractChannelIDFromFriendlyRef(channelRef)
	if !ok {
		return echo.NewHTTPError(http.StatusBadRequest, "invalid channel reference")
	}

	return c.serveHostedPlayerByID(ctx, tenant, channelIDStr)
}

// ServeHostedPlayerByCode serves channel player by short 6-char code: /live/:channelCode
func (c *ChannelController) ServeHostedPlayerByCode(ctx echo.Context) error {
	tenant := resolveTenantForLive(ctx)
	channelCode := strings.ToUpper(strings.TrimSpace(ctx.Param("channelCode")))
	if len(channelCode) != 6 {
		return echo.NewHTTPError(http.StatusBadRequest, "channel code must be 6 characters")
	}

	requestCtx := context.WithValue(ctx.Request().Context(), "tenantSlug", tenant)
	ctx.SetRequest(ctx.Request().WithContext(requestCtx))

	mtq, err := db.NewMultiTenantQuerierByContext(ctx, c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	channels, err := mtq.Querier.GetAllChannels(ctx.Request().Context())
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	for _, channel := range channels {
		channelID := utils.UuidBytesToString(channel.ID.Bytes)
		if shortCodeFromChannelID(channelID) == channelCode {
			return c.serveHostedPlayerByID(ctx, tenant, channelID)
		}
	}

	return echo.NewHTTPError(http.StatusNotFound, "channel code not found")
}

func (c *ChannelController) renderHostedPage(ctx echo.Context, tenantBytes, channelIDBytes, channelNameBytes []byte) error {
	page := fmt.Sprintf(`<!doctype html>
<html>
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>Channel Live Player</title>
  <style>
    html,body { margin:0; padding:0; width:100%%; height:100%%; background:#000; color:#fff; font-family:system-ui,sans-serif; overflow:hidden; }
    #root { position:relative; width:100%%; height:100%%; }
    #content { position:absolute; inset:0; background:#000; }
    .zone { position:absolute; overflow:hidden; background:#050505; }
    .zone img,.zone video { width:100%%; height:100%%; object-fit:cover; display:block; }
    .zone-empty { width:100%%; height:100%%; display:flex; align-items:center; justify-content:center; color:#94a3b8; font-size:13px; }
    #overlay { position:absolute; left:12px; bottom:12px; background:rgba(0,0,0,0.45); padding:8px 10px; border-radius:8px; font-size:12px; }
  </style>
</head>
<body>
  <div id="root">
    <div id="content"></div>
    <div id="overlay">Loading channel...</div>
  </div>
  <script>
    const tenantId = %s;
    const channelId = %s;
    const channelName = %s;
    const baseUrl = window.location.origin;
    const overlay = document.getElementById('overlay');
    const contentEl = document.getElementById('content');
    let zoneTimers = {};
    let ws = null;
    let wsReconnectTimer = null;

    function toMins(value) {
      if (!value || typeof value !== 'string') return null;
      const parts = value.split(':').map(Number);
      if (parts.length < 2 || parts.some(Number.isNaN)) return null;
      const h = parts[0] || 0;
      const m = parts[1] || 0;
      return h * 60 + m;
    }
    function parseDuration(value) {
      if (!value || typeof value !== 'string') return 15000;
      const parts = value.split(':').map(Number);
      if (parts.length === 3 && parts.every((n) => Number.isFinite(n))) {
        return (parts[0] * 3600 + parts[1] * 60 + parts[2]) * 1000;
      }
      if (/^\d+$/.test(value)) return Number(value) * 1000;
      return 15000;
    }

    function stopZonePlayback() {
      Object.values(zoneTimers).forEach((timerId) => clearTimeout(timerId));
      zoneTimers = {};
    }

    function toPercent(value, fallback) {
      if (typeof value === 'number' && Number.isFinite(value)) return value;
      if (typeof value === 'string') {
        const parsed = Number(String(value).replace('%%', '').trim());
        if (Number.isFinite(parsed)) return parsed;
      }
      return fallback;
    }

    function clampPercent(value) {
      return Math.max(0, Math.min(100, value));
    }

    function extractLayoutZones(layout) {
      if (!layout || !layout.zones) {
        return [{ id: 'zone-1', name: 'Main', position: 1, x: 0, y: 0, width: 100, height: 100 }];
      }

      const source = layout.zones;
      const toZone = (raw, index, fallbackKey) => {
        const entry = raw || {};
        const width = clampPercent(toPercent(entry.width, 100));
        const height = clampPercent(toPercent(entry.height, 100));
        const x = clampPercent(toPercent(entry.x, 0));
        const y = clampPercent(toPercent(entry.y, 0));
        return {
          id: (entry.id && String(entry.id).trim()) || fallbackKey || ('zone-' + (index + 1)),
          name: (entry.name && String(entry.name).trim()) || fallbackKey || ('Zone ' + (index + 1)),
          position: index + 1,
          x: Math.min(x, 100 - width),
          y: Math.min(y, 100 - height),
          width: width,
          height: height
        };
      };

      if (Array.isArray(source)) {
        const zones = source.map((entry, index) => toZone(entry, index, 'zone-' + (index + 1)));
        return zones.length > 0 ? zones : [{ id: 'zone-1', name: 'Main', position: 1, x: 0, y: 0, width: 100, height: 100 }];
      }

      if (typeof source === 'object' && source !== null) {
        const entries = Object.entries(source);
        if (entries.length > 0) {
          return entries.map(([key, entry], index) => toZone(entry, index, key));
        }
      }

      return [{ id: 'zone-1', name: 'Main', position: 1, x: 0, y: 0, width: 100, height: 100 }];
    }

    function createZoneElements(zones) {
      contentEl.innerHTML = '';
      const byPosition = new Map();

      zones.forEach((zone) => {
        const zoneEl = document.createElement('div');
        zoneEl.className = 'zone';
        zoneEl.style.left = zone.x + '%%';
        zoneEl.style.top = zone.y + '%%';
        zoneEl.style.width = zone.width + '%%';
        zoneEl.style.height = zone.height + '%%';
        zoneEl.dataset.zoneName = zone.name;
        zoneEl.innerHTML = '<div class="zone-empty">' + zone.name + '</div>';
        contentEl.appendChild(zoneEl);
        byPosition.set(zone.position, zoneEl);
      });

      return byPosition;
    }

    function resolveContent(item, contentMap) {
      const contentId = item.content_id || item.contentId;
      if (item.content && typeof item.content === 'object') {
        return item.content;
      }
      return contentMap.get(contentId);
    }

    function renderItemInZone(zoneEl, item, contentMap) {
      const content = resolveContent(item, contentMap);
      const contentId = item.content_id || item.contentId;
      const url = content && (content.full_url || content.fullUrl || content.file_path || content.filePath);
      if (!url) {
        zoneEl.innerHTML = '<div class="zone-empty">No media URL</div>';
        return;
      }

      const type = String((content && (content.content_type || content.contentType || content.type)) || '').toLowerCase();
      if (type.startsWith('video')) {
        zoneEl.innerHTML = '<video src="' + String(url) + '" autoplay muted playsinline></video>';
      } else {
        zoneEl.innerHTML = '<img src="' + String(url) + '" alt="' + String(contentId || 'content') + '" />';
      }
    }

    function normalizePlaylistItems(payload) {
      const source = Array.isArray(payload && payload.items) ? payload.items : [];
      return source
        .map((entry) => (entry && entry.playlist_item ? entry.playlist_item : entry))
        .filter(Boolean)
        .filter((item) => Boolean(item.is_active ?? item.isActive ?? true))
        .sort((a, b) => {
          const laneA = Number(a.layout_position ?? a.layoutPosition ?? 1);
          const laneB = Number(b.layout_position ?? b.layoutPosition ?? 1);
          if (laneA !== laneB) return laneA - laneB;
          return Number(a.order ?? 0) - Number(b.order ?? 0);
        });
    }

    function startZoneLoops(items, zones, zoneElementsByPosition, contentMap) {
      const itemsByZone = new Map();
      items.forEach((item) => {
        const lane = Number(item.layout_position ?? item.layoutPosition ?? 1);
        if (!itemsByZone.has(lane)) itemsByZone.set(lane, []);
        itemsByZone.get(lane).push(item);
      });

      zones.forEach((zone) => {
        const laneItems = itemsByZone.get(zone.position) || [];
        const zoneEl = zoneElementsByPosition.get(zone.position);
        if (!zoneEl || laneItems.length === 0) {
          return;
        }

        let laneIndex = 0;
        const playNext = () => {
          const item = laneItems[laneIndex %% laneItems.length];
          renderItemInZone(zoneEl, item, contentMap);
          laneIndex += 1;
          zoneTimers[zone.position] = setTimeout(playNext, parseDuration(item.timestring || item.timeString));
        };

        playNext();
      });
    }

    async function loadAndPlay() {
      try {
        stopZonePlayback();
        const [schedulesRes, contentsRes] = await Promise.all([
          fetch(baseUrl + '/api/channels/' + encodeURIComponent(channelId) + '/schedules', { headers: { 'X-Tenant-ID': tenantId } }),
          fetch(baseUrl + '/api/contents', { headers: { 'X-Tenant-ID': tenantId } })
        ]);
        if (!schedulesRes.ok) throw new Error('Unable to load schedules');
        if (!contentsRes.ok) throw new Error('Unable to load contents');
        const schedules = await schedulesRes.json();
        const contentsPayload = await contentsRes.json();
        const contents = Array.isArray(contentsPayload) ? contentsPayload : (contentsPayload.data || []);
        const contentMap = new Map(contents.map((c) => [c.id, c]));

        const now = new Date();
        const day = now.getDay() === 0 ? 7 : now.getDay();
        const mins = now.getHours() * 60 + now.getMinutes();
        const active = (schedules || []).find((s) => {
          const d = Number(s.day || 0);
          const start = toMins(s.start_datetime);
          const end = toMins(s.end_datetime);
          return (d === 0 || d === day) && start !== null && end !== null && mins >= start && mins < end;
        });
        if (!active || !active.playlist_id) {
          overlay.textContent = channelName + ' • No active schedule';
          contentEl.innerHTML = '<div style="padding:24px;font-size:24px">No active schedule</div>';
          return;
        }

        const playlistRes = await fetch(baseUrl + '/api/playlists/' + encodeURIComponent(active.playlist_id), {
          headers: { 'X-Tenant-ID': tenantId }
        });
        if (!playlistRes.ok) throw new Error('Unable to load playlist');
        const playlistPayload = await playlistRes.json();
        const items = normalizePlaylistItems(playlistPayload);
        const zones = extractLayoutZones(playlistPayload.layout);

        if (!items.length) {
          overlay.textContent = channelName + ' • No active items';
          contentEl.innerHTML = '<div style="padding:24px;font-size:24px">No active playlist items</div>';
          return;
        }

        const zoneElementsByPosition = createZoneElements(zones);
        startZoneLoops(items, zones, zoneElementsByPosition, contentMap);
        overlay.textContent = channelName + ' • ' + zones.length + ' zone(s) • ' + items.length + ' item(s)';
      } catch (err) {
        stopZonePlayback();
        overlay.textContent = 'Playback error';
        contentEl.innerHTML = '<div style="padding:24px;font-size:20px">Error loading channel playback</div>';
      }
    }

    function connectChannelSync() {
      if (ws) {
        try { ws.close(); } catch (_) {}
      }
      const protocol = window.location.protocol === 'https:' ? 'wss:' : 'ws:';
      const wsUrl = protocol + '//' + window.location.host + '/ws/channel?tenant=' + encodeURIComponent(tenantId) + '&channelId=' + encodeURIComponent(channelId);
      ws = new WebSocket(wsUrl);
      ws.onopen = function() {
        overlay.textContent = channelName + ' • Live';
      };
      ws.onmessage = function(event) {
        try {
          const msg = JSON.parse(event.data);
          if (msg && msg.action === 'content-sync') {
            loadAndPlay();
          }
        } catch (_) {
          loadAndPlay();
        }
      };
      ws.onclose = function() {
        if (wsReconnectTimer) clearTimeout(wsReconnectTimer);
        wsReconnectTimer = setTimeout(connectChannelSync, 3000);
      };
      ws.onerror = function() {
        try { ws.close(); } catch (_) {}
      };
    }

    loadAndPlay();
    connectChannelSync();
    setInterval(loadAndPlay, 60000);
  </script>
</body>
</html>`, string(tenantBytes), string(channelIDBytes), string(channelNameBytes))

	return ctx.HTML(http.StatusOK, page)
}

