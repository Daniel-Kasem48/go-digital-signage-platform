func (c *ChannelController) GetByID(ctx echo.Context) error {
	ID := ctx.Param("id")

	uuId, err := utils.ParseAndConvertUUID(ID)
	if err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "Invalid UUID format")
	}

	mtq, err := db.NewMultiTenantQuerierByContext(ctx, c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	channel, err := mtq.Querier.GetChannelById(ctx.Request().Context(), uuId)
	if err != nil {
		if err.Error() == "sql: no rows in result set" {
			return echo.NewHTTPError(http.StatusNotFound, "Channel not found")
		}
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	return ctx.JSON(http.StatusOK, channel)
}

