func (c *ChannelController) Publish(ctx echo.Context) error {
	ID := ctx.Param("id")

	input := new(PublishChannelDto)

	if err := ctx.Bind(input); err != nil {
		return ctx.JSON(http.StatusBadRequest, map[string]string{"error": "Invalid input" + err.Error()})
	}

	if err := c.validator.ValidateAndReturnErrors(input); err != nil {
		return err
	}

	uuId, err := utils.ParseAndConvertUUID(ID)
	if err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "Invalid UUID format")
	}

	params := models.UpdateDevicesActiveChannelParams{
		ActiveChannelID: uuId,
		Column2:         input.DeviceIds,
	}

	mtq, err := db.NewMultiTenantQuerierByContext(ctx, c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	previouslyAssignedDevices, err := mtq.Querier.GetDevicesByChannelID(ctx.Request().Context(), uuId)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	if err = mtq.Querier.UpdateDevicesActiveChannel(ctx.Request().Context(), params); err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	targetDeviceMap := make(map[string]struct{}, len(input.DeviceIds))
	for _, deviceID := range input.DeviceIds {
		if deviceID.Valid {
			targetDeviceMap[utils.UuidBytesToString(deviceID.Bytes)] = struct{}{}
		}
	}

	removedDeviceIDs := make([]models.Device, 0)
	for _, device := range previouslyAssignedDevices {
		deviceIDKey := utils.UuidBytesToString(device.ID.Bytes)
		if _, stillAssigned := targetDeviceMap[deviceIDKey]; stillAssigned {
			continue
		}
		removedDeviceIDs = append(removedDeviceIDs, device)
	}

	for _, device := range removedDeviceIDs {
		if err = mtq.Querier.UpdateDevice(ctx.Request().Context(), models.UpdateDeviceParams{
			ID:              device.ID,
			Name:            device.Name,
			Code:            device.Code,
			ActiveChannelID: pgtype.UUID{},
			Orientation:     device.Orientation,
			IpAddress:       device.IpAddress,
			LastActiveAt:    device.LastActiveAt,
		}); err != nil {
			return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
		}
	}

	if err = c.contentSyncService.NotifyDevices(ctx, input.DeviceIds); err != nil {
		fmt.Printf("failed to notify assigned devices: %v\n", err)
	}

	removedPGUUIDs := make([]pgtype.UUID, 0, len(removedDeviceIDs))
	for _, removedDevice := range removedDeviceIDs {
		removedPGUUIDs = append(removedPGUUIDs, removedDevice.ID)
	}
	if err = c.contentSyncService.NotifyDevicesCleared(removedPGUUIDs); err != nil {
		fmt.Printf("failed to notify unassigned devices: %v\n", err)
	}

	result := c.deviceDisplayService.GetDevicesPlaylistItems(ctx, input.DeviceIds)
	return ctx.JSON(http.StatusOK, result)
}
