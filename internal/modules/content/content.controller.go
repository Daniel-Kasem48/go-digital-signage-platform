// generateFullURL creates direct MinIO URL (assumes public bucket)
func (c *ContentController) generateFullURL(ctx echo.Context, filePath *string) *string {
	if filePath == nil || *filePath == "" {
		return nil
	}

	path := strings.TrimLeft(*filePath, "/")
	if path == "" {
		return nil
	}

	if cdnPrefix := strings.TrimSpace(c.config.CDNPrefix); cdnPrefix != "" {
		fullURL := fmt.Sprintf("%s/%s", strings.TrimRight(cdnPrefix, "/"), path)
		return &fullURL
	}

	endpoint := strings.TrimSpace(c.config.AWSEndpoint)
	bucket := strings.Trim(strings.TrimSpace(c.config.AWSBucket), "/")
	if endpoint == "" || bucket == "" {
		return nil
	}

	fullURL := fmt.Sprintf("%s/%s/%s", strings.TrimRight(endpoint, "/"), bucket, path)
	return &fullURL
}

// convertToResponseDTO converts model.Content to ContentResponseDto with full URLs
func (c *ContentController) convertToResponseDTO(ctx echo.Context, content models.Content) dto.ContentResponseDto {
	responseDto := dto.ContentResponseDto{
		ID:          content.ID,
		Name:        content.Name,
		ContentType: string(content.ContentType),
		CreatedAt:   content.CreatedAt.Time.Format(time.RFC3339),
		UpdatedAt:   content.UpdatedAt.Time.Format(time.RFC3339),
	}

	// Add file path and full URL for media content
	if content.FilePath != nil {
		responseDto.FilePath = content.FilePath
		responseDto.FullURL = c.generateFullURL(ctx, content.FilePath)
	}

	// Add schema for template content
	if content.Schema != nil {
		var schemaObj interface{}
		if err := json.Unmarshal(content.Schema, &schemaObj); err == nil {
			responseDto.Schema = schemaObj
		}
	}

	// Add template ID if present
	if content.TemplateID.Valid {
		templateId := content.TemplateID.Bytes
		if len(templateId) == 16 {
			// Convert UUID bytes to string
			templateIdStr := fmt.Sprintf("%x-%x-%x-%x-%x",
				templateId[0:4], templateId[4:6], templateId[6:8], templateId[8:10], templateId[10:16])
			responseDto.TemplateID = &templateIdStr
		}
	}

	return responseDto
}

func (c *ContentController) List(ctx echo.Context) error {
	offset, limit := common.HandleLimitAndOffsetFromCtx(ctx)

	mtq, err := db.NewMultiTenantQuerierByContext(ctx, c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	contents, err := mtq.Querier.ListContents(ctx.Request().Context(),
		models.ListContentsParams{
			Limit:  int32(limit),
			Offset: int32(offset),
		})

	if contents == nil {
		contents = []models.Content{} // Assuming `Layout` is the struct type for your layouts
	}
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	// Convert to response DTOs with full URLs
	contentResponseDtos := make([]dto.ContentResponseDto, len(contents))
	for i, content := range contents {
		contentResponseDtos[i] = c.convertToResponseDTO(ctx, content)
	}

	count, _ := mtq.Querier.ContentsCount(ctx.Request().Context())
	response, _ := common.FetchPaginatedResponse(contentResponseDtos, count, limit, offset)
	return ctx.JSON(http.StatusOK, response)
}

func (c *ContentController) Create(ctx echo.Context) error {
	input := new(dto.CreateContentDto)
	var err error

	// Log the raw request body for debugging
	body := ctx.Request().Body
	defer body.Close()
	bodyBytes, _ := io.ReadAll(body)
	fmt.Printf("Raw request body: %s\n", string(bodyBytes))

	// Reset the body for binding
	ctx.Request().Body = io.NopCloser(bytes.NewReader(bodyBytes))

	// Bind the input
	if err := ctx.Bind(input); err != nil {
		fmt.Printf("Bind error: %v\n", err)
		return ctx.JSON(http.StatusBadRequest, map[string]string{"error": "Invalid input"})
	}

	fmt.Printf("Bound input: %+v\n", input)

	if err := c.validator.ValidateAndReturnErrors(input); err != nil {
		fmt.Printf("Validation error: %v\n", err)
		return err // Make sure you return the error here
	}

	// Create content from template
	createdEntity, err := c.contentService.CreateFromTemplate(ctx, input)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	// Sync all devices with active channels so players can pick up content changes immediately.
	if err := c.contentSyncService.NotifyAllDevicesByChannel(ctx); err != nil {
		fmt.Printf("failed to notify devices after template content create: %v\n", err)
	}

	// Convert to response DTO with full URL
	responseDto := c.convertToResponseDTO(ctx, *createdEntity)
	return ctx.JSON(http.StatusOK, responseDto)
}

// CreateMedia handles media content upload (images and videos)
