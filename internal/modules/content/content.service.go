func NewContentService(
	pool *pgxpool.Pool,
	fileService *file.FileService,
	dbPool *pgxpool.Pool,
	) *ContentService {
	queries := models.New(pool) // Initialize the queries using sqlc-generated code

	return &ContentService{Queries: queries,fileService: fileService, dbPool: dbPool}
}

