func (s *ContentService) CreateFromMedia(ctx echo.Context,input *dto.CreateMediaContentDto) (*models.Content, error) {
	contentGeneratedId:=uuid.New()

	updatedFilePath :="content/"+ strings.TrimPrefix(input.TempFilePath, "temp/")
	_, err := s.fileService.CopyObject(input.TempFilePath, updatedFilePath)
	if err != nil {
		return nil, err
	}
	createContentParams := models.CreateContentParams{
		ID:          input.ContentType + "_" + contentGeneratedId.String(),
		Name:        input.Name,
		ContentType: models.ContentType(input.ContentType),
		FilePath:    &updatedFilePath,
	}

	mtq ,err:= db.NewMultiTenantQuerierByContext(ctx,s.dbPool)
	if err != nil {
		return nil,err
	}

	createdContent,err := mtq.Querier.CreateContent(ctx.Request().Context(),createContentParams)
	if err != nil {
		//if pgErr, ok := err.(*pgconn.PgError); ok && pgErr.Code == UniqueViolation {
		//	return nil, fmt.Errorf("content name is duplicated")
		//}
		return nil, fmt.Errorf("failed to save content: %w", err)
	}

	return &createdContent, nil
}

func (s *ContentService) DeleteByID(ctx echo.Context, contentID string) error {
	mtq, err := db.NewMultiTenantQuerierByContext(ctx, s.dbPool)
	if err != nil {
		return err
	}

	content, err := mtq.Querier.GetContentById(ctx.Request().Context(), contentID)
	if err != nil {
		return err
	}

	if err := mtq.Querier.DeleteContentById(ctx.Request().Context(), contentID); err != nil {
		return err
	}

	if content.FilePath != nil && *content.FilePath != "" {
		if _, err := s.fileService.DeleteObject(*content.FilePath); err != nil {
			// Keep DB delete successful even if object cleanup fails.
			fmt.Printf("failed to delete object for content %s: %v\n", contentID, err)
		}
	}

	return nil
}

func IsContentNotFound(err error) bool {
	return err == sql.ErrNoRows
}
