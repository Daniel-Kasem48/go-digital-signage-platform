func (c *DeviceGroupController) List(ctx echo.Context) error {
	mtq ,err:= db.NewMultiTenantQuerierByContext(ctx,c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	entities, err := mtq.Querier.ListDeviceGroups(ctx.Request().Context())
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}
	if entities == nil {
		entities = []models.DeviceGroup{}
	}
	return ctx.JSON(http.StatusOK, entities)
}

func (c *DeviceGroupController) Create(ctx echo.Context) error {
	input := new(CreateDeviceGroupApiParams)
	if err := ctx.Bind(input); err != nil {
		return ctx.JSON(http.StatusBadRequest, map[string]string{"error": "Invalid input"+err.Error()})
	}
	if err := c.validator.ValidateAndReturnErrors(input); err != nil {
		return err
	}

	mtq ,err:= db.NewMultiTenantQuerierByContext(ctx,c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	 err = mtq.Querier.CreateDeviceGroup(ctx.Request().Context(), input.Name)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	return ctx.JSON(http.StatusOK, "")
}


