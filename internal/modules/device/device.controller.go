package device

import (
	"digital-signage/internal/common"
	"digital-signage/internal/db"
	models "digital-signage/internal/db/autogenerated"
	"digital-signage/internal/handlers"
	content_sync "digital-signage/internal/modules/content-sync"
	"digital-signage/internal/modules/utils"
	"github.com/jackc/pgx/v5/pgtype"
	"github.com/jackc/pgx/v5/pgxpool"
	"github.com/labstack/echo/v4"
	"net/http"
)

type DeviceController struct {
	deviceService      *DeviceService
	datasourceService  *db.DatasourceService
	validator          *handlers.CustomValidator
	contentSyncService *content_sync.ContentSyncService
	dbPool             *pgxpool.Pool
}

func NewDeviceController(
	deviceService *DeviceService,
	datasourceService *db.DatasourceService,
	validator *handlers.CustomValidator,
	contentSyncService *content_sync.ContentSyncService,
	dbPool *pgxpool.Pool,

) *DeviceController {
	return &DeviceController{
		deviceService:      deviceService,
		datasourceService:  datasourceService,
		validator:          validator,
		contentSyncService: contentSyncService,
		dbPool:             dbPool,
	}
}

func (c *DeviceController) RegisterRoutes(parent *echo.Group) {
	g := parent.Group("/devices")

	// Only public device routes should be here (e.g., device registration)
	// Temporary GET route to test tenant middleware
	g.GET("/list", c.List)
}

// RegisterBackendRoutes registers routes for backend-to-backend communication
func (c *DeviceController) RegisterBackendRoutes(parent *echo.Group) {
	g := parent.Group("/devices")

	// Backend routes - no additional tenant middleware needed as it's already applied
	g.GET("", c.List)
	g.DELETE("/:id", c.Delete)
	// Add more backend-specific routes here as needed
}

func (c *DeviceController) List(ctx echo.Context) error {
	offset, limit := common.HandleLimitAndOffsetFromCtx(ctx)

	mtq, err := db.NewMultiTenantQuerierByContext(ctx, c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	entities, err := mtq.Querier.ListDevices(ctx.Request().Context(), models.ListDevicesParams{
		Limit:  int32(limit),
		Offset: int32(offset),
	})

	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}
	if entities == nil {
		entities = []models.Device{}
	}

	count, _ := mtq.Querier.DevicesCount(ctx.Request().Context())

	response, err := common.FetchPaginatedResponse(entities, count, limit, offset)
	if err != nil {
		return err
	}
	return ctx.JSON(http.StatusOK, response)
}

func (c *DeviceController) Delete(ctx echo.Context) error {
	ID := ctx.Param("id")

	uuId, err := utils.ParseAndConvertUUID(ID)
	if err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "Invalid UUID format")
	}

	mtq, err := db.NewMultiTenantQuerierByContext(ctx, c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	if err = c.contentSyncService.NotifyDevicesCleared([]pgtype.UUID{uuId}); err != nil {
		// Non-blocking: device may already be offline/disconnected.
	}

	err = mtq.Querier.DeleteDevice(ctx.Request().Context(), uuId)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	return ctx.JSON(http.StatusOK, "")
}
