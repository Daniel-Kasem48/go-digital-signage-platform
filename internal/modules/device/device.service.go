package device

import (
	"digital-signage/internal/db"
	models "digital-signage/internal/db/autogenerated"
	"digital-signage/internal/modules/tenant"
	"github.com/jackc/pgx/v5/pgtype"
	"github.com/jackc/pgx/v5/pgxpool"
	"github.com/labstack/echo/v4"
)

type DeviceService struct {
	tenantManager *tenant.TenantManager
	dbPool *pgxpool.Pool
}

func NewDeviceService(
	tenantManager *tenant.TenantManager,
	dbPool *pgxpool.Pool,

	) *DeviceService {
	return &DeviceService{
		tenantManager: tenantManager,
		dbPool: dbPool,
	}
}


func (s *DeviceService) RegisterDeviceTransaction(ctx echo.Context, createDeviceParams models.CreateDeviceParams, challengeId pgtype.UUID) (models.Device, error) {
	requestContext := ctx.Request().Context()
	
	// Get a connection from the pool and start a transaction
	conn, err := s.dbPool.Acquire(requestContext)
	if err != nil {
		return models.Device{}, err
	}
	defer conn.Release()
	
	tx, err := conn.Begin(requestContext)
	if err != nil {
		return models.Device{}, err // Return an empty device and the error
	}
	defer tx.Rollback(requestContext) // Rollback if Commit is not called

	// Create transaction-aware Queries instance
	// Use tenant from middleware context
	mtq, err := db.NewMultiTenantQuerierByContext(ctx, tx)
	if err != nil {
		return models.Device{}, err
	}
	// Create transaction-aware Queries instance
	qtx := mtq.Querier.WithTx(tx)

	createdDevice, err := qtx.CreateDevice(requestContext, createDeviceParams)
	if err != nil {
		return models.Device{}, err // Return an empty device and the error
	}

	err = qtx.DeleteAuthChallengeById(requestContext, challengeId)
	if err != nil {
		return models.Device{}, err // Return an empty device and the error
	}

	// Commit the transaction
	if err := tx.Commit(requestContext); err != nil {
		return models.Device{}, err // Return an empty device and the error
	}

	return createdDevice, nil
}
