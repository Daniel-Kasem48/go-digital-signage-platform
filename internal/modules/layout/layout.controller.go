package layout

import (
	"digital-signage/internal/db"
	models "digital-signage/internal/db/autogenerated"
	"digital-signage/internal/handlers"
	"digital-signage/internal/modules/utils"
	"encoding/json"
	"github.com/google/uuid"
	"github.com/jackc/pgx/v5/pgxpool"
	"github.com/labstack/echo/v4"
	"net/http"
	"time"
)

type LayoutController struct {
	dataSourceService *db.DatasourceService
	validator         *handlers.CustomValidator
	dbPool *pgxpool.Pool
}

func NewLayoutController(
	dataSourceService *db.DatasourceService,
	validator *handlers.CustomValidator,
	dbPool *pgxpool.Pool,
) *LayoutController {
	return &LayoutController{
		dataSourceService: dataSourceService,
		validator:         validator,
		dbPool: dbPool,
	}
}

func (c *LayoutController) RegisterRoutes(parent *echo.Group) {
	g := parent.Group("/layouts")

	g.GET("", c.List)
	g.GET("/:id", c.GetByID)
	g.POST("", c.Create)
	g.PUT("/:id", c.Update)
	g.DELETE("/:id", c.Delete)
}

func (c *LayoutController) RegisterBackendRoutes(parent *echo.Group) {
	g := parent.Group("/layouts")

	g.GET("", c.List)
	g.GET("/:id", c.GetByID)
	g.POST("", c.Create)
	g.PUT("/:id", c.Update)
	g.DELETE("/:id", c.Delete)
}

// convertToResponseDTO converts models.Layout to LayoutResponseDTO with proper JSON handling
func (c *LayoutController) convertToResponseDTO(layout models.Layout) LayoutResponseDTO {
	responseDto := LayoutResponseDTO{
		ID:        uuid.UUID(layout.ID.Bytes).String(),
		Name:      layout.Name,
		CreatedAt: layout.CreatedAt.Time.Format(time.RFC3339),
		UpdatedAt: layout.UpdatedAt.Time.Format(time.RFC3339),
	}

	// Properly unmarshal zones from byte array to interface{}
	if layout.Zones != nil {
		var zonesObj interface{}
		if err := json.Unmarshal(layout.Zones, &zonesObj); err == nil {
			responseDto.Zones = zonesObj
		}
	}

	return responseDto
}

func (c *LayoutController) List(ctx echo.Context) error {
	mtq ,err:= db.NewMultiTenantQuerierByContext(ctx,c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}
	layouts, err := mtq.Querier.ListLayouts(ctx.Request().Context())
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	if layouts == nil {
		layouts = []models.Layout{}
	}

	// Convert to response DTOs with proper JSON handling
	layoutResponseDtos := make([]LayoutResponseDTO, len(layouts))
	for i, layout := range layouts {
		layoutResponseDtos[i] = c.convertToResponseDTO(layout)
	}

	return ctx.JSON(http.StatusOK, layoutResponseDtos)
}

func (c *LayoutController) Create(ctx echo.Context) error {
	input := new(CreateLayoutDTO)
	if err := ctx.Bind(input); err != nil {
		return ctx.JSON(http.StatusBadRequest, map[string]string{"error": "Invalid input"})
	}
	if err := c.validator.ValidateAndReturnErrors(input); err != nil {
		return err
	}

	createLayoutParams := models.CreateLayoutParams{
		Name:  input.Name,
		Zones: input.Zones,
	}

	mtq ,err:= db.NewMultiTenantQuerierByContext(ctx,c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}
	createdEntity, err := mtq.Querier.CreateLayout(ctx.Request().Context(), createLayoutParams)

	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	// Convert to response DTO with proper JSON handling
	responseDto := c.convertToResponseDTO(createdEntity)
	return ctx.JSON(http.StatusOK, responseDto)
}

func (c *LayoutController) GetByID(ctx echo.Context) error {
	ID := ctx.Param("id")

	uuId, err := utils.ParseAndConvertUUID(ID)
	if err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "Invalid UUID format")
	}

	mtq, err := db.NewMultiTenantQuerierByContext(ctx, c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	layout, err := mtq.Querier.GetLayoutByID(ctx.Request().Context(), uuId)
	if err != nil {
		return echo.NewHTTPError(http.StatusNotFound, "Layout not found")
	}

	// Convert to response DTO with proper JSON handling
	responseDto := c.convertToResponseDTO(layout)
	return ctx.JSON(http.StatusOK, responseDto)
}

func (c *LayoutController) Update(ctx echo.Context) error {
	ID := ctx.Param("id")

	uuId, err := utils.ParseAndConvertUUID(ID)
	if err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "Invalid UUID format")
	}

	input := new(UpdateLayoutDTO)
	if err := ctx.Bind(input); err != nil {
		return ctx.JSON(http.StatusBadRequest, map[string]string{"error": "Invalid input"})
	}

	if err := c.validator.ValidateAndReturnErrors(input); err != nil {
		return err
	}

	updateParams := models.UpdateLayoutParams{
		ID:    uuId,
		Name:  input.Name,
		Zones: input.Zones,
	}

	mtq, err := db.NewMultiTenantQuerierByContext(ctx, c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	updatedEntity, err := mtq.Querier.UpdateLayout(ctx.Request().Context(), updateParams)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	// Convert to response DTO with proper JSON handling
	responseDto := c.convertToResponseDTO(updatedEntity)
	return ctx.JSON(http.StatusOK, responseDto)
}

func (c *LayoutController) Delete(ctx echo.Context) error {
	ID := ctx.Param("id")

	uuId, err := utils.ParseAndConvertUUID(ID)
	if err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "Invalid UUID format")
	}

	mtq, err := db.NewMultiTenantQuerierByContext(ctx, c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	err = mtq.Querier.DeleteLayout(ctx.Request().Context(), uuId)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	return ctx.JSON(http.StatusOK, map[string]string{"message": "Layout deleted successfully"})
}
