type PlaylistItemController struct {
	datasourceService  *db.DatasourceService
	validator          *handlers.CustomValidator
	contentSyncService *content_sync.ContentSyncService
	dbPool             *pgxpool.Pool
}

func NewPlaylistItemController(
	datasourceService *db.DatasourceService,
	validator *handlers.CustomValidator,
	contentSyncService *content_sync.ContentSyncService,
	dbPool *pgxpool.Pool,
) *PlaylistItemController {
	return &PlaylistItemController{
		datasourceService:  datasourceService,
		validator:          validator,
		contentSyncService: contentSyncService,
		dbPool:             dbPool,
	}
}

func toPlaylistItemDbError(err error, fallbackMsg string) error {
	var pgErr *pgconn.PgError
	if errors.As(err, &pgErr) && pgErr.Code == "23505" {
		return echo.NewHTTPError(http.StatusConflict, "Duplicate playlist item: this content already exists in the target playlist/zone.")
	}
	return echo.NewHTTPError(http.StatusInternalServerError, fallbackMsg+err.Error())
}

func (c *PlaylistItemController) validateDuplicateAssignment(
	ctx echo.Context,
	playlistID pgtype.UUID,
	layoutPosition int32,
	contentID string,
	excludeItemID *pgtype.UUID,
) error {
	mtq, err := db.NewMultiTenantQuerierByContext(ctx, c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	items, err := mtq.Querier.GetPlaylistItemsByPlaylistId(ctx.Request().Context(), playlistID)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "Failed to check existing playlist items: "+err.Error())
	}

	targetContentID := strings.TrimSpace(strings.ToLower(contentID))
	for _, item := range items {
		if excludeItemID != nil && item.ID == *excludeItemID {
			continue
		}
		if item.LayoutPosition != layoutPosition {
			continue
		}
		if strings.TrimSpace(strings.ToLower(item.ContentID)) != targetContentID {
			continue
		}
		return echo.NewHTTPError(
			http.StatusConflict,
			fmt.Sprintf("Content is already assigned in layout position %d for this playlist. Choose another zone or content.", layoutPosition),
		)
	}

	return nil
}

// validateLayoutPosition validates that the layout position is valid for the given playlist's layout
func (c *PlaylistItemController) validateLayoutPosition(ctx echo.Context, playlistId pgtype.UUID, layoutPosition int32) error {
	mtq, err := db.NewMultiTenantQuerierByContext(ctx, c.dbPool)
	if err != nil {
		return fmt.Errorf("database error: %v", err)
	}

	// Get the playlist to find its layout_id
	playlist, err := mtq.Querier.GetPlaylistByID(ctx.Request().Context(), playlistId)
	if err != nil {
		return fmt.Errorf("playlist not found: %v", err)
	}

	// If playlist has no layout, any position is invalid (should be 0 or 1 for full-screen)
	if !playlist.LayoutID.Valid {
		if layoutPosition != 1 {
			return fmt.Errorf("playlist has no layout assigned, layout position must be 1 for full-screen content")
		}
		return nil
	}

	// Get the layout to check its zones
	layout, err := mtq.Querier.GetLayoutByID(ctx.Request().Context(), playlist.LayoutID)
	if err != nil {
		return fmt.Errorf("layout not found: %v", err)
	}

	// Parse the layout zones to count them
	var zoneCount int
	if layout.Zones != nil {
		// Try parsing as array first (database format)
		var zoneArray []map[string]interface{}
		if err := json.Unmarshal(layout.Zones, &zoneArray); err == nil {
			zoneCount = len(zoneArray)
		} else {
			// Fallback: try parsing as object
			var zoneObject map[string]interface{}
			if err := json.Unmarshal(layout.Zones, &zoneObject); err == nil {
				zoneCount = len(zoneObject)
			} else {
				return fmt.Errorf("invalid layout zones format")
			}
		}
	}

	// Validate layout position is within range (1-based indexing)
	if layoutPosition < 1 || layoutPosition > int32(zoneCount) {
		return fmt.Errorf("layout position %d is invalid, must be between 1 and %d (number of zones in layout '%s')", layoutPosition, zoneCount, layout.Name)
	}

	return nil
}

func (c *PlaylistItemController) RegisterRoutes(parent *echo.Group) {
	g := parent.Group("/playlist-items")

	g.GET("", c.List)
	g.POST("", c.Create)
	g.PUT("/:id", c.Update)
	g.DELETE("/:id", c.Delete)
}

func (c *PlaylistItemController) RegisterBackendRoutes(parent *echo.Group) {
	g := parent.Group("/playlist-items")

	g.GET("", c.List)
	g.POST("", c.Create)
	g.PUT("/:id", c.Update)
	g.DELETE("/:id", c.Delete)

}

func (c *PlaylistItemController) List(ctx echo.Context) error {
	ID := ctx.QueryParam("playlistId")

	uuId, err := utils.ParseAndConvertUUID(ID)
	if err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "Invalid UUID format")
	}

	mtq, err := db.NewMultiTenantQuerierByContext(ctx, c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	entities, err := mtq.Querier.GetPlaylistItemsByPlaylistId(ctx.Request().Context(), uuId)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}
	return ctx.JSON(http.StatusOK, entities)
}

func (c *PlaylistItemController) Create(ctx echo.Context) error {
	input := new(CreatePlaylistItemDto)
	if err := ctx.Bind(input); err != nil {
		return ctx.JSON(http.StatusBadRequest, map[string]string{"error": "Invalid input: " + err.Error()})
	}

	if err := c.validator.ValidateAndReturnErrors(input); err != nil {
		return err
	}

	// Validate layout position against playlist layout
	if err := c.validateLayoutPosition(ctx, input.PlaylistId, input.LayoutPosition); err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "Invalid layout position: "+err.Error())
	}
	if err := c.validateDuplicateAssignment(ctx, input.PlaylistId, input.LayoutPosition, input.ContentID, nil); err != nil {
		return err
	}

	mtq, err := db.NewMultiTenantQuerierByContext(ctx, c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}
	lastOrderInterface, err := mtq.Querier.GetLastPlaylistItemOrder(ctx.Request().Context(), input.PlaylistId)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "Failed to fetch last order: "+err.Error())
	}

	newOrder := lastOrderInterface.(int32) + 1

	createParams := models.CreatePlaylistItemParams{
		Order:          newOrder,
		LayoutPosition: input.LayoutPosition,
		Timestring:     input.Timestring,
		IsActive:       input.IsActive,
		ContentID:      input.ContentID,
		PlaylistID:     input.PlaylistId,
	}

	createdEntity, err := mtq.Querier.CreatePlaylistItem(ctx.Request().Context(), createParams)
	if err != nil {
		return toPlaylistItemDbError(err, "Failed to create playlist item: ")
	}

	// Notify devices affected by this playlist change
	if err := c.contentSyncService.NotifyDevicesByPlaylistId(ctx, input.PlaylistId); err != nil {
		fmt.Printf("Failed to notify devices of playlist change: %v\n", err)
	}

	return ctx.JSON(http.StatusOK, createdEntity)
}

func (c *PlaylistItemController) Update(ctx echo.Context) error {
	ID := ctx.Param("id")

	uuId, err := utils.ParseAndConvertUUID(ID)
	if err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "Invalid UUID format")
	}

	input := new(UpdatePlaylistItemDto)
	if err := ctx.Bind(input); err != nil {
		return ctx.JSON(http.StatusBadRequest, map[string]string{"error": "Invalid input: " + err.Error()})
	}

	if err := c.validator.ValidateAndReturnErrors(input); err != nil {
		return err
	}

	mtq, err := db.NewMultiTenantQuerierByContext(ctx, c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	// First, get the current playlist item
	currentItem, err := mtq.Querier.GetPlaylistItemById(ctx.Request().Context(), uuId)
	if err != nil {
		return echo.NewHTTPError(http.StatusNotFound, "Playlist item not found")
	}

	// Build update params, using current values for fields not provided in the request
	updateParams := models.UpdatePlaylistItemParams{
		ID:             uuId,
		Order:          currentItem.Order,
		LayoutPosition: currentItem.LayoutPosition,
		Timestring:     currentItem.Timestring,
		IsActive:       currentItem.IsActive,
		ContentID:      currentItem.ContentID,
		PlaylistID:     currentItem.PlaylistID,
	}

	// Override with provided values (partial update)
	if input.Order != nil {
		updateParams.Order = *input.Order
	}
	if input.LayoutPosition != nil {
		updateParams.LayoutPosition = *input.LayoutPosition
	}
	if input.Timestring != nil {
		updateParams.Timestring = *input.Timestring
	}
	if input.IsActive != nil {
		updateParams.IsActive = *input.IsActive
	}
	if input.ContentID != nil {
		updateParams.ContentID = *input.ContentID
	}
	if input.PlaylistId != nil {
		updateParams.PlaylistID = *input.PlaylistId
	}

	// Validate layout position if it's being changed
	if input.LayoutPosition != nil {
		playlistIdToValidate := updateParams.PlaylistID
		if input.PlaylistId != nil {
			playlistIdToValidate = *input.PlaylistId
		}
		if err := c.validateLayoutPosition(ctx, playlistIdToValidate, *input.LayoutPosition); err != nil {
			return echo.NewHTTPError(http.StatusBadRequest, "Invalid layout position: "+err.Error())
		}
	}
	if err := c.validateDuplicateAssignment(ctx, updateParams.PlaylistID, updateParams.LayoutPosition, updateParams.ContentID, &uuId); err != nil {
		return err
	}

	err = mtq.Querier.UpdatePlaylistItem(ctx.Request().Context(), updateParams)
	if err != nil {
		return toPlaylistItemDbError(err, "Failed to update playlist item: ")
	}

	updatedEntity, err := mtq.Querier.GetPlaylistItemById(ctx.Request().Context(), uuId)
	if err != nil {
		return echo.NewHTTPError(http.StatusNotFound, "Playlist item not found after update")
	}

	// Notify devices affected by this playlist change
	if err := c.contentSyncService.NotifyDevicesByPlaylistId(ctx, updatedEntity.PlaylistID); err != nil {
		fmt.Printf("Failed to notify devices of playlist change: %v\n", err)
	}

	return ctx.JSON(http.StatusOK, updatedEntity)
}

func (c *PlaylistItemController) Delete(ctx echo.Context) error {
	ID := ctx.Param("id")

	uuId, err := utils.ParseAndConvertUUID(ID)
	if err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "Invalid UUID format")
	}

	mtq, err := db.NewMultiTenantQuerierByContext(ctx, c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	// Get the playlist item before deletion to know which playlist is affected
	playlistItem, err := mtq.Querier.GetPlaylistItemById(ctx.Request().Context(), uuId)
	if err != nil {
		return echo.NewHTTPError(http.StatusNotFound, "Playlist item not found")
	}

	err = mtq.Querier.DeletePlaylistItem(ctx.Request().Context(), uuId)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	// Notify devices affected by this playlist change
	if err := c.contentSyncService.NotifyDevicesByPlaylistId(ctx, playlistItem.PlaylistID); err != nil {
		fmt.Printf("Failed to notify devices of playlist change: %v\n", err)
	}

	return ctx.JSON(http.StatusOK, "")
}
