func (c *PlaylistController) List(ctx echo.Context) error {
	mtq ,err:= db.NewMultiTenantQuerierByContext(ctx,c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	entities, err := mtq.Querier.ListPlaylists(ctx.Request().Context())
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}
	if entities == nil {
		entities = []models.Playlist{}
	}

	return ctx.JSON(http.StatusOK, entities)
}

func (c *PlaylistController) GetByID(ctx echo.Context) error {
	ID := ctx.Param("id")

	uuId, err := utils.ParseAndConvertUUID(ID)
	if err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "Invalid UUID format")
	}

	mtq, err := db.NewMultiTenantQuerierByContext(ctx, c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	// Get the playlist
	playlist, err := mtq.Querier.GetPlaylistByID(ctx.Request().Context(), uuId)
	if err != nil {
		return echo.NewHTTPError(http.StatusNotFound, "Playlist not found")
	}

	// Get the layout
	layout, err := mtq.Querier.GetLayoutByID(ctx.Request().Context(), playlist.LayoutID)
	if err != nil {
		// If layout not found, set layout to nil but continue
		layout = models.Layout{}
	}

	// Get playlist items
	items, err := mtq.Querier.GetPlaylistItemsByPlaylistId(ctx.Request().Context(), uuId)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "Failed to fetch playlist items: "+err.Error())
	}

	// Ensure items is not nil
	if items == nil {
		items = []models.PlaylistItem{}
	}

	// Fetch content for each playlist item
	itemsWithContent := make([]PlaylistItemWithContent, len(items))
	for i, item := range items {
		// Get content for this item
		content, err := mtq.Querier.GetContentById(ctx.Request().Context(), item.ContentID)
		if err != nil {
			// If content not found, set content to nil but continue
			itemsWithContent[i] = PlaylistItemWithContent{
				PlaylistItem: item,
				Content:      nil,
			}
		} else {
			itemsWithContent[i] = PlaylistItemWithContent{
				PlaylistItem: item,
				Content:      &content,
			}
		}
	}

	// Get channels linked to this playlist
	channels, err := mtq.Querier.GetChannelsByPlaylistID(ctx.Request().Context(), uuId)
	if err != nil {
		// If channels not found, set channels to empty array but continue
		channels = []models.GetChannelsByPlaylistIDRow{}
	}

	// Create flat response structure (embedded playlist fields + layout + items)
	var layoutPtr *models.Layout
	if layout.ID.Valid {
		layoutPtr = &layout
	}
	
	response := PlaylistWithItemsDto{
		Playlist: playlist,
		Layout:   layoutPtr,
		Items:    itemsWithContent,
		Channels: channels,
	}

	return ctx.JSON(http.StatusOK, response)
}

func (c *PlaylistController) Create(ctx echo.Context) error {
	input := new(CreatePlaylistDto)
	if err := ctx.Bind(input); err != nil {
		return ctx.JSON(http.StatusBadRequest, map[string]string{"error": "Invalid input"+err.Error()})
	}

	if err := c.validator.ValidateAndReturnErrors(input); err != nil {
		return err
	}

	//jsonLayout,_:=json.Marshal(input.Layout)
	createParams:=models.CreatePlaylistParams{
		Name:   input.Name,
		LayoutID: input.LayoutID,
	}

	mtq ,err:= db.NewMultiTenantQuerierByContext(ctx,c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}
	createdEntity, err := mtq.Querier.CreatePlaylist(ctx.Request().Context(), createParams)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	return ctx.JSON(http.StatusOK, createdEntity)
}

func (c *PlaylistController) Update(ctx echo.Context) error {
	ID := ctx.Param("id")

	uuId, err := utils.ParseAndConvertUUID(ID)
	if err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "Invalid UUID format")
	}

	input := new(UpdatePlaylistDto)
	if err := ctx.Bind(input); err != nil {
		return ctx.JSON(http.StatusBadRequest, map[string]string{"error": "Invalid input"+err.Error()})
	}

	if err := c.validator.ValidateAndReturnErrors(input); err != nil {
		return err
	}

	updateParams := models.UpdatePlaylistParams{
		ID:       uuId,
		Name:     input.Name,
		LayoutID: input.LayoutID,
	}

	mtq, err := db.NewMultiTenantQuerierByContext(ctx, c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	err = mtq.Querier.UpdatePlaylist(ctx.Request().Context(), updateParams)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	updatedEntity, err := mtq.Querier.GetPlaylistByID(ctx.Request().Context(), uuId)
	if err != nil {
		return echo.NewHTTPError(http.StatusNotFound, "Playlist not found after update")
	}

	return ctx.JSON(http.StatusOK, updatedEntity)
}

func (c *PlaylistController) Delete(ctx echo.Context) error {
	ID := ctx.Param("id")

	uuId, err := utils.ParseAndConvertUUID(ID)
	if err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "Invalid UUID format")
	}

	mtq ,err:= db.NewMultiTenantQuerierByContext(ctx,c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}
	err = mtq.Querier.DeletePlaylist(ctx.Request().Context(), uuId)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	return ctx.JSON(http.StatusOK, "")
}
