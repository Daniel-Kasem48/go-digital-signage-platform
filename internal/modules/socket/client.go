const (
	// Max wait time when writing message to peer
	//10
	writeWait = 10 * time.Second

	//60
	// Max time till next pong from peer
	pongWait = 60 * time.Second

	// Send ping interval, must be less then pong wait time
	pingPeriod = (pongWait * 9) / 10

	// Maximum message size allowed from peer.
	maxMessageSize = 10000
)

var (
	newline = []byte{'\n'}
	space   = []byte{' '}
)

var upgrader = websocket.Upgrader{
	ReadBufferSize:  4096,
	WriteBufferSize: 4096,
	CheckOrigin: func(r *http.Request) bool {
		// Allow all connections by returning true
		// For more security, you can check r.Header.Get("Origin") here
		return true
	},
}

// Client represents the websocket client at the server
type Client struct {
	// The actual websocket connection.
	conn          *websocket.Conn
	wsServer      *WsServer
	send          chan []byte
	ID            uuid.UUID `json:"id"`
	rooms         map[string]bool
	roomsMu       sync.RWMutex
	device        models.Device
	deviceSession bool
}

func newClient(conn *websocket.Conn, wsServer *WsServer, deviceId pgtype.UUID) *Client {
	device, _ := wsServer.datasourceService.Queries.GetDevice(context.TODO(), deviceId)

	return &Client{
		ID:            uuid.New(),
		conn:          conn,
		wsServer:      wsServer,
		send:          make(chan []byte, 256),
		rooms:         make(map[string]bool),
		device:        device,
		deviceSession: true,
	}
}

func newAnonymousClient(conn *websocket.Conn, wsServer *WsServer) *Client {
	return &Client{
		ID:            uuid.New(),
		conn:          conn,
		wsServer:      wsServer,
		send:          make(chan []byte, 256),
		rooms:         make(map[string]bool),
		deviceSession: false,
	}
}

func (client *Client) readPump() {
	defer func() {
		// Call disconnect method to handle room leaving and publishing events
		client.disconnect()
	}()

	client.conn.SetReadLimit(maxMessageSize)
	client.conn.SetReadDeadline(time.Now().Add(pongWait))
	client.conn.SetPongHandler(func(string) error {
		client.conn.SetReadDeadline(time.Now().Add(pongWait))
		return nil
	})

	// Start endless read loop, waiting for messages from client
	for {
		_, jsonMessage, err := client.conn.ReadMessage()
		if err != nil {
			if websocket.IsUnexpectedCloseError(err, websocket.CloseGoingAway, websocket.CloseAbnormalClosure) {
				log.Printf("unexpected close error: %v", err)
			}
			break
		}

		client.handleNewMessage(jsonMessage)
	}
}

func (client *Client) writePump() {
	ticker := time.NewTicker(pingPeriod)
	defer func() {
		ticker.Stop()
		client.conn.Close()
	}()
	for {
		select {
		case message, ok := <-client.send:
			client.conn.SetWriteDeadline(time.Now().Add(writeWait))
			if !ok {
				// The WsServer closed the channel.
				client.conn.WriteMessage(websocket.CloseMessage, []byte{})
				return
			}

			w, err := client.conn.NextWriter(websocket.TextMessage)
			if err != nil {
				return
			}
			w.Write(message)

			// Attach queued chat messages to the current websocket message.
			n := len(client.send)
			for i := 0; i < n; i++ {
				w.Write(newline)
				w.Write(<-client.send)
			}

			if err := w.Close(); err != nil {
				return
			}
		case <-ticker.C:
			client.conn.SetWriteDeadline(time.Now().Add(writeWait))
			if err := client.conn.WriteMessage(websocket.PingMessage, nil); err != nil {
				return
			}
			if client.deviceSession {
				client.updateLastActive()
			}
		}
	}
}

func (client *Client) disconnect() {
	fmt.Println("Disconnecting client......", client.ID)

	for _, roomName := range client.roomNames() {
		err := client.wsServer.LeaveRoom(roomName, client)
		if err != nil {
			fmt.Println("error while leaving room "+roomName, err)
		}
	}
	client.wsServer.unregister <- client
	client.conn.Close()
}

func (client *Client) updateLastActive() {
	if client.wsServer.natsService == nil {
		return
	}

	bucket, err := client.wsServer.natsService.GetDeviceLastActiveBucket()
	if err != nil {
		log.Printf("failed to get device activity bucket: %v", err)
		return
	}

	now := time.Now()
	timeAsBytes, err := now.MarshalJSON()
	if err != nil {
		log.Printf("failed to marshal current time: %v", err)
		return
	}

	deviceID := utils.UuidBytesToString(client.device.ID.Bytes)
	lastActiveEntry, err := bucket.Get(deviceID)

	var lastStoredActive time.Time
	if err == nil && lastActiveEntry != nil {
		err = json.Unmarshal(lastActiveEntry.Value(), &lastStoredActive)
		if err != nil {
			fmt.Println("Error unmarshaling last active time:", err)
		}
	} else if errors.Is(err, nats.ErrKeyNotFound) || errors.Is(err, nats.ErrKeyDeleted) {
		lastStoredActive = time.Time{} // Zero value for time
	} else {
		log.Printf("failed to fetch last active timestamp for device %s: %v", deviceID, err)
		return
	}

	if !client.device.LastActiveAt.Valid {
		// Initialize LastActiveAt if it's not valid
		client.device.LastActiveAt = pgtype.Timestamp{
			Time:             now,
			InfinityModifier: 0,
			Valid:            true,
		}
	}

	timeDiff := math.Abs(float64(client.device.LastActiveAt.Time.Unix() - lastStoredActive.Unix()))
	if lastActiveEntry == nil || timeDiff > 1*60 {
		fmt.Println("Should Update Last Active since diff >", timeDiff, "seconds")
		fmt.Println("client.device.LastActiveAt.Time.Unix():", client.device.LastActiveAt.Time.Unix())
		fmt.Println("lastStoredActive.Unix():", lastStoredActive.Unix())

		// Fetch current device state to preserve active_channel_id
		currentDevice, err := client.wsServer.datasourceService.Queries.GetDevice(context.TODO(), client.device.ID)
		if err != nil {
			fmt.Println("Failed to fetch current device state:", err)
			return
		}

		// Update the device's last active time in the database
		params := models.UpdateDeviceParams{
			ID:              client.device.ID,
			Name:            currentDevice.Name,
			Code:            currentDevice.Code,
			ActiveChannelID: currentDevice.ActiveChannelID, // Preserve current active_channel_id
			Orientation:     "landscape",                   // Fixed value to avoid schema mismatch
			IpAddress:       client.device.IpAddress,
			LastActiveAt: pgtype.Timestamp{
				Time:             now,
				InfinityModifier: 0,
				Valid:            true,
			},
		}

		err = client.wsServer.datasourceService.Queries.UpdateDevice(context.TODO(), params)

		if err != nil {
			fmt.Println("Failed to update device last active in DB:", err)
		}
		client.device.LastActiveAt = params.LastActiveAt
	}

	_, err = bucket.Put(deviceID, timeAsBytes)
	if err != nil {
		log.Printf("Failed to update last active for device %s: %v", client.ID, err)
	}
}

func ServeWs(wsServer *WsServer, w http.ResponseWriter, r *http.Request) {
	// Extract token from query parameters (e.g., ws://example.com/ws?token=abc)
	tokenString, ok := r.URL.Query()["token"]
	if !ok || len(tokenString[0]) < 1 {
		log.Println("URL Param 'token' is missing")
		http.Error(w, "Forbidden", http.StatusForbidden)
		return
	}

	// Validate the token
	token, err := validateToken(tokenString[0], wsServer.cfg.DeviceSecret)
	if err != nil || !token.Valid {
		log.Println("Invalid token:", err)
		http.Error(w, "Forbidden", http.StatusForbidden)
		return
	}

	// Extract claims
	var deviceId string
	if claims, ok := token.Claims.(jwt.MapClaims); ok && token.Valid {

		if id, ok := claims["deviceID"].(string); ok {
			deviceId = id
		} else {
			http.Error(w, "Forbidden", http.StatusForbidden)
			return
		}
	} else {
		http.Error(w, "Forbidden", http.StatusForbidden)
		return
	}

	// Upgrade the HTTP connection to a WebSocket connection
	conn, err := upgrader.Upgrade(w, r, nil)
	if err != nil {
		log.Println("Upgrade error:", err)
		http.Error(w, "Internal Server Error", http.StatusInternalServerError)
		return
	}

	// Parse the deviceID string to uuid.UUID
	parsedUUID, err := uuid.Parse(deviceId)
	if err != nil {
		log.Println("Failed to parse deviceID to UUID:", err)
		http.Error(w, "Forbidden", http.StatusForbidden)
		return
	}

	// Convert the uuid.UUID to pgtype.UUID
	deviceUUID := pgtype.UUID{
		Bytes: [16]byte(parsedUUID[:]),
		Valid: true,
	}
	// Initialize the client and start its read/write pumps
	client := newClient(conn, wsServer, deviceUUID)

	//Join the device to room with device_ prefix to match API expectations
	err = wsServer.JoinRoom("device_"+deviceId, client)

	if err != nil {
		http.Error(w, "Failed to create room", http.StatusInternalServerError)
		return
	}
	fmt.Println("........New Client ", client.ID)

	go client.writePump()
	go client.readPump()

	wsServer.register <- client
}

// ServeChannelWs upgrades a public websocket for hosted channel players.
func ServeChannelWs(wsServer *WsServer, w http.ResponseWriter, r *http.Request) {
	channelID := strings.TrimSpace(r.URL.Query().Get("channelId"))
	tenant := strings.TrimSpace(r.URL.Query().Get("tenant"))
	if channelID == "" || tenant == "" {
		http.Error(w, "channelId and tenant are required", http.StatusBadRequest)
		return
	}

	if _, err := uuid.Parse(channelID); err != nil {
		http.Error(w, "invalid channelId", http.StatusBadRequest)
		return
	}

	conn, err := upgrader.Upgrade(w, r, nil)
	if err != nil {
		log.Println("Upgrade error:", err)
		http.Error(w, "Internal Server Error", http.StatusInternalServerError)
		return
	}

	client := newAnonymousClient(conn, wsServer)
	roomName := "channel_" + tenant + "_" + channelID
	if err := wsServer.JoinRoom(roomName, client); err != nil {
		http.Error(w, "Failed to join channel room", http.StatusInternalServerError)
		return
	}

	go client.writePump()
	go client.readPump()
	wsServer.register <- client
}

// validateToken validates the JWT token
func validateToken(tokenString string, jwtSecret string) (*jwt.Token, error) {
	// Parse the token
	token, err := jwt.Parse(tokenString, func(token *jwt.Token) (interface{}, error) {
		// Verify the token's signing method etc.
		if _, ok := token.Method.(*jwt.SigningMethodHMAC); !ok {
			return nil, fmt.Errorf("unexpected signing method: %v", token.Header["alg"])
		}
		// Return the secret key used to sign the token
		return []byte(jwtSecret), nil
	})

	return token, err
}

