func (client *Client) isInRoom(roomName string) bool {
	client.roomsMu.RLock()
	defer client.roomsMu.RUnlock()

	if _, ok := client.rooms[roomName]; ok {
		return true
	}

	return false
}

func (client *Client) markRoomJoined(roomName string) {
	if roomName == "" {
		return
	}

	client.roomsMu.Lock()
	client.rooms[roomName] = true
	client.roomsMu.Unlock()
}

func (client *Client) markRoomLeft(roomName string) {
	if roomName == "" {
		return
	}

	client.roomsMu.Lock()
	delete(client.rooms, roomName)
	client.roomsMu.Unlock()
}

func (client *Client) roomNames() []string {
	client.roomsMu.RLock()
	defer client.roomsMu.RUnlock()

	rooms := make([]string, 0, len(client.rooms))
	for roomName := range client.rooms {
		rooms = append(rooms, roomName)
	}

	return rooms
}

