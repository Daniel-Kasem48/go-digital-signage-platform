type TemplateService struct {
	Queries *models.Queries
	fileService *file.FileService
	cfg         *config.Config
	dbPool      *pgxpool.Pool
}

func NewTemplateService(pool *pgxpool.Pool,fileService *file.FileService,cfg *config.Config) *TemplateService {
	queries := models.New(pool) // Initialize the queries using sqlc-generated code
	return &TemplateService{Queries: queries,fileService: fileService,cfg: cfg, dbPool: pool}
}

func (svc *TemplateService) Create(ctx echo.Context, input *TemplateInput) (*models.Template, error) {
	// Validate input
	if input.Name == "" {
		return nil, fmt.Errorf("template name is required")
	}
	if input.StorageKey == "" {
		return nil, fmt.Errorf("storage key is required")
	}

	fmt.Printf("Creating template: %s with storage key: %s\n", input.Name, input.StorageKey)

	// Get tenant-aware querier
	mtq, err := db.NewMultiTenantQuerierByContext(ctx, svc.dbPool)
	if err != nil {
		return nil, fmt.Errorf("failed to create tenant querier: %w", err)
	}

	createTemplateParams:=models.CreateTemplateParams{
		Name:           input.Name,
		StorageKey:           &input.StorageKey,
		ThumbnailStorageKey: &input.ThumbnailStorageKey,
		Schema:         nil,
	}

	savedTemplate, err := mtq.Querier.CreateTemplate(ctx.Request().Context(), createTemplateParams)
	if err != nil {
		return nil, fmt.Errorf("failed to create template in database: %w", err)
	}

	fmt.Printf("Template created in DB with ID: %s\n", utils.UuidBytesToString(savedTemplate.ID.Bytes))

	// Generate the S3 key for the template
	templateS3Key := utils.GenerateS3TemplateIdentifier(utils.UuidBytesToString(savedTemplate.ID.Bytes))
	fmt.Printf("Generated S3 key: %s\n", templateS3Key)

	// Copy the object to the new S3 location
	_,err = svc.fileService.CopyObject(input.StorageKey, templateS3Key)
	if err != nil {
		return nil, fmt.Errorf("failed to copy template to S3: %w", err)
	}

	// Upload the template files and get the schema
	fmt.Println("Starting template files upload and schema extraction...")
	schema, err := svc.UploadTemplateFiles(savedTemplate, templateS3Key)
	if err != nil {
		return nil, fmt.Errorf("failed to upload template files and extract schema: %w", err)
	}

	fmt.Printf("Schema extraction completed. Schema length: %d bytes\n", len(schema))

	// Update the template data
	savedTemplate.StorageKey = &input.StorageKey

	//TODO work here
	// Check if a thumbnail key is provided and upload the image if so
	//if input.ThumbnailS3Key != "" {
	//	thumbnailS3Key, err := svc.fileService.UploadImage(input.ThumbnailS3Key, S3DirTemplates)
	//	if err != nil {
	//		return nil, err
	//	}
	//	savedTemplate.ThumbnailS3Key = thumbnailS3Key
	//}

	updateParams:=models.UpdateTemplateParams{
		ID:             savedTemplate.ID,
		Name:           savedTemplate.Name,
		StorageKey:          savedTemplate.StorageKey,
		ThumbnailStorageKey: savedTemplate.ThumbnailStorageKey,
		Schema:         schema,
	}
	
	fmt.Printf("Updating template in database with schema length: %d bytes\n", len(schema))
	fmt.Printf("Update params - ID: %s, Schema length: %d\n", utils.UuidBytesToString(savedTemplate.ID.Bytes), len(updateParams.Schema))
	
	// Save the updated template data
	 err = mtq.Querier.UpdateTemplate(ctx.Request().Context(), updateParams)
	if err != nil {
		fmt.Printf("Error updating template: %v\n", err)
		return nil, err
	}
	
	fmt.Printf("Template updated successfully in database\n")

	return &savedTemplate, nil
}


func (svc *TemplateService) UploadTemplateFiles(template models.Template, templateS3Key string) ([]byte, error) {
	fmt.Printf("Uploading template files from S3 key: %s\n", templateS3Key)
	
	// Get the template zip from S3
	s3Template, err := svc.fileService.S3Client.GetObject(context.TODO(), &s3.GetObjectInput{
		Bucket: aws.String(svc.cfg.AWSBucket),
		Key:    aws.String(templateS3Key),
	})

	if err != nil {
		return nil, fmt.Errorf("failed to get template from S3: %w", err)
	}
	defer s3Template.Body.Close()

	// Create a zip reader from the S3 object
	buf := new(bytes.Buffer)
	if _, err := io.Copy(buf, s3Template.Body); err != nil {
		return nil, fmt.Errorf("failed to read template from S3: %w", err)
	}
	
	fmt.Printf("Downloaded template zip, size: %d bytes\n", buf.Len())
	
	zipReader, err := zip.NewReader(bytes.NewReader(buf.Bytes()), int64(buf.Len()))
	if err != nil {
		return nil, fmt.Errorf("failed to create zip reader: %w", err)
	}

	fmt.Printf("Zip reader created, found %d files in archive\n", len(zipReader.File))

	var schema []byte
	var uploadErrors []error

	// Iterate through the files in the zip archive
	for _, singleFile := range zipReader.File {
		fileName := strings.Replace(singleFile.Name, "\\", "/", -1)
		fmt.Printf("Processing file: '%s'\n", fileName)
		
		fileReader, err := singleFile.Open()
		if err != nil {
			fmt.Printf("Error opening file %s: %v\n", fileName, err)
			uploadErrors = append(uploadErrors, fmt.Errorf("failed to open file %s: %w", fileName, err))
			continue
		}

		// Read the file content into a buffer to make it seekable
		fileContent := new(bytes.Buffer)
		if _, err := io.Copy(fileContent, fileReader); err != nil {
			fmt.Printf("Error reading file %s: %v\n", fileName, err)
			uploadErrors = append(uploadErrors, fmt.Errorf("failed to read file %s: %w", fileName, err))
			fileReader.Close()
			continue
		}
		fileReader.Close()

		// Log the filename first
		fmt.Printf("Processing file: '%s'\n", fileName)
		
		// Check if the file is schema.json (at any level)
		isSchemaFile := strings.HasSuffix(strings.ToLower(fileName), "schema.json")
		fmt.Printf("Checking if '%s' ends with 'schema.json': %v\n", fileName, isSchemaFile)
		if isSchemaFile {
			fmt.Printf("Found schema.json! Content length: %d bytes\n", fileContent.Len())
			schema = fileContent.Bytes()
			previewLen := len(schema)
			if previewLen > 100 {
				previewLen = 100
			}
			fmt.Printf("Schema content preview: %s\n", string(schema[:previewLen]))
		}

		// Handle the file upload to S3
		uploadParams := &s3.PutObjectInput{
			Bucket:      aws.String(svc.cfg.AWSBucket),
			Key:         aws.String(filepath.Join(utils.S3DirTemplates, utils.UuidBytesToString(template.ID.Bytes), fileName)),
			Body:        bytes.NewReader(fileContent.Bytes()), // Pass the seekable buffer
			ContentType: aws.String(mime.TypeByExtension(filepath.Ext(fileName))),
		}

		fmt.Println("Uploading file:", fileName, "to S3 key:", filepath.Join(utils.S3DirTemplates, utils.UuidBytesToString(template.ID.Bytes), fileName))
		if _, err := svc.fileService.S3Client.PutObject(context.TODO(), uploadParams); err != nil {
			uploadErrors = append(uploadErrors, err)
		}
	}

	if len(uploadErrors) > 0 {
		fmt.Printf("Upload errors occurred: %d errors\n", len(uploadErrors))
		for i, err := range uploadErrors {
			fmt.Printf("Error %d: %v\n", i+1, err)
		}
		return nil, fmt.Errorf("failed to upload %d files: %v", len(uploadErrors), uploadErrors[0])
	}

	// Validate that schema.json was found
	if schema == nil || len(schema) == 0 {
		fmt.Println("ERROR: schema.json not found or empty in template zip file")
		return nil, errors.New("schema.json not found in template zip file - please ensure your template includes a valid schema.json at the root level")
	}

	fmt.Printf("Schema extraction successful! Returning %d bytes\n", len(schema))
	return schema, nil
}


