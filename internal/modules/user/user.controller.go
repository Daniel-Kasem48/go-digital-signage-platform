package user

import (
	"digital-signage/internal/db"
	models "digital-signage/internal/db/autogenerated"
	"digital-signage/internal/handlers"
	"digital-signage/internal/modules/utils"
	"github.com/jackc/pgx/v5/pgxpool"
	"github.com/labstack/echo/v4"
	"net/http"
)

type UserController struct {
	datasourceService *db.DatasourceService
	validator         *handlers.CustomValidator
	dbPool *pgxpool.Pool
}

func NewUserController(
	datasourceService *db.DatasourceService,
	validator     *handlers.CustomValidator,
	dbPool *pgxpool.Pool,

	) *UserController {
	return &UserController{
		datasourceService: datasourceService,
		validator     :    validator,
		 dbPool: dbPool,
	}
}

func (c *UserController) RegisterRoutes(parent *echo.Group) {
	g := parent.Group("/users")

	g.GET("", c.List)
	g.POST("",c.Create)
	g.DELETE("",c.Delete)
}

func (c *UserController) RegisterBackendRoutes(parent *echo.Group) {
	g := parent.Group("/users")

	g.GET("", c.List)
	g.POST("",c.Create)
	g.DELETE("",c.Delete)
}

func (c *UserController) Create(ctx echo.Context) error {
	input := new(ApiCreateUserParams)
	if err := ctx.Bind(input); err != nil {
		return ctx.JSON(http.StatusBadRequest, map[string]string{"error": "Invalid input"+err.Error()})
	}

	if err := c.validator.ValidateAndReturnErrors(input); err != nil {
		return err
	}

	mtq ,err:= db.NewMultiTenantQuerierByContext(ctx,c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}
	createParams:=models.CreateUserParams{
		Username: input.Username,
		Password: input.Password,
	}
	err = mtq.Querier.CreateUser(ctx.Request().Context(), createParams)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	return ctx.JSON(http.StatusOK, "")
}

func (c *UserController) List(ctx echo.Context) error {
	mtq ,err:= db.NewMultiTenantQuerierByContext(ctx,c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	entities, err := mtq.Querier.ListUsers(ctx.Request().Context())
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}
	if entities == nil {
		entities = []models.User{}
	}

	return ctx.JSON(http.StatusOK, entities)
}

func (c *UserController) Delete(ctx echo.Context) error {
	ID := ctx.Param("id")

	uuId, err := utils.ParseAndConvertUUID(ID)
	if err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "Invalid UUID format")
	}

	mtq ,err:= db.NewMultiTenantQuerierByContext(ctx,c.dbPool)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}
	err = mtq.Querier.DeleteUser(ctx.Request().Context(), uuId)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, err.Error())
	}

	return ctx.JSON(http.StatusOK, "")
}
